/**
 * Example Astro Configuration with Mermaid Support
 *
 * This file shows how to integrate the remark-mermaid plugin
 * into the p5.js-website Astro configuration.
 *
 * @see https://github.com/processing/p5.js-website/issues/168
 */

import { defineConfig, passthroughImageService } from 'astro/config';
import preact from '@astrojs/preact';
import mdx from '@astrojs/mdx';
import tailwind from '@astrojs/tailwind';

// Import the custom Mermaid plugin
import { remarkMermaid } from './src/plugins/remark-mermaid.mjs';

// Additional remark plugins (if needed)
import remarkGfm from 'remark-gfm';

// Rehype plugins for HTML processing
import rehypeRaw from 'rehype-raw';

export default defineConfig({
  site: 'https://p5js.org',

  // ==========================================================================
  // Markdown Configuration
  // ==========================================================================
  markdown: {
    // Add remarkMermaid to the remark plugins array
    // Order matters: remarkMermaid should run before other transformations
    remarkPlugins: [
      remarkMermaid,  // <-- Add this plugin
      remarkGfm,
    ],

    // Rehype plugins for processing the HTML output
    rehypePlugins: [
      // rehype-raw is needed to preserve the HTML generated by remarkMermaid
      rehypeRaw,
    ],

    // Syntax highlighting configuration
    shikiConfig: {
      theme: 'github-light',
    },
  },

  // ==========================================================================
  // Integrations
  // ==========================================================================
  integrations: [
    // Preact for UI components
    preact({ compat: true }),

    // MDX support - also needs the remark plugin
    mdx({
      // The MDX integration inherits from markdown config by default,
      // but you can explicitly add plugins here if needed
      remarkPlugins: [
        remarkMermaid,  // <-- Also add here for MDX files
        remarkGfm,
      ],
      rehypePlugins: [
        rehypeRaw,
      ],
    }),

    // Tailwind CSS
    tailwind(),

    // ... other integrations
  ],

  // ==========================================================================
  // Build Configuration
  // ==========================================================================
  build: {
    format: 'directory',
  },

  // ==========================================================================
  // Output Configuration
  // ==========================================================================
  output: 'static',

  // ==========================================================================
  // Image Service (preserve existing config)
  // ==========================================================================
  image: {
    service: passthroughImageService(),
    domains: ['openprocessing.org'],
  },

  // ==========================================================================
  // Prefetch Configuration
  // ==========================================================================
  prefetch: {
    prefetchAll: true,
    defaultStrategy: 'viewport',
  },

  // ==========================================================================
  // Trailing Slash Configuration
  // ==========================================================================
  trailingSlash: 'always',
});
